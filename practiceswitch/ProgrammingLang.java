package practiceswitch;

public class ProgrammingLang {
	

		public static void main(String args[]) {

			int language = 1;

			switch(language) {

			case 1:
				System.out.println("Java");
				break;

			case 2:
				System.out.println("Python");
				break;

			case 3:
				System.out.println("C++");
				break;

			case 4:
				System.out.println("JavaScript");
				break;

			}

		}

	}

